"""Vision source labels (audit §3.12) - one vocabulary, one choke point.

Every image that crosses the perception boundary carries one of these labels,
so the model always knows what it is looking at: a webcam frame is the USER,
a screen capture is the COMPUTER, a file is one the user handed over, a
generated image is JARVIS's own work, a browser screenshot is a WEBPAGE.
What each label *means* is explained once, in core/prompt.txt's [SELF] block.

Two send paths exist and both go through here:

* main Live session   - main.py ``_flush_pending_vision`` -> ``source_text``
* one-shot side calls - core/gemini.py ``call`` -> ``with_source_label``

The labels are opaque to the model in itself (there is no API field for
"where did this come from"); they are a text convention, which is exactly
why there must be one place that defines them and tests that guard it.
"""
from __future__ import annotations

SCREEN     = "screen"
CAMERA     = "camera"
USER_IMAGE = "user_image"
GENERATED  = "generated_image"
BROWSER    = "browser"

#: The complete set of sources an image may arrive with. Anything not in
#: here is a programming error, not a model error - see ``label_for``.
SOURCES = (SCREEN, CAMERA, USER_IMAGE, GENERATED, BROWSER)

_LABELS = {
    SCREEN:     "[IMAGE SOURCE: SCREEN CAPTURE]",
    CAMERA:     "[IMAGE SOURCE: WEBCAM]",
    USER_IMAGE: "[IMAGE SOURCE: USER-PROVIDED FILE]",
    GENERATED:  "[IMAGE SOURCE: GENERATED BY JARVIS]",
    BROWSER:    "[IMAGE SOURCE: BROWSER SCREENSHOT]",
}


def label_for(source: str) -> str:
    """The label for ``source``.

    Unknown sources raise: silently sending an image unlabelled is the exact
    failure §3.12 exists to stop, so a bad source must fail loud at the
    boundary rather than degrade to a wrong label.
    """
    try:
        return _LABELS[source]
    except KeyError:
        raise ValueError(
            f"unknown vision source {source!r}; expected one of {SOURCES}"
        ) from None


def source_text(source: str, text: str) -> str:
    """Label + text - the main-session shape (label leads the text part)."""
    return f"{label_for(source)}\n\n{text}"


def is_image_item(item) -> bool:
    """True when a contents item carries image pixels.

    Covers every shape a caller can hand us: a genai ``Part`` with
    ``inline_data``, a ``dict`` part (the Live wire format), a bare PIL
    image (file_processor's shape), or an object with an ``image/*`` mime.
    Text is never a source of ambiguity here - a labelled pure-text call
    makes no sense, so strings and bytes are not images.
    """
    if item is None or isinstance(item, (str, bytes)):
        return False
    if isinstance(item, dict):
        return bool(item.get("inline_data") or item.get("file_data"))
    if getattr(item, "inline_data", None) is not None:
        return True
    if str(getattr(item, "mime_type", "") or "").startswith("image/"):
        return True
    try:
        from PIL import Image
    except ImportError:
        return False
    return isinstance(item, Image.Image)


def with_source_label(contents, source):
    """Insert ``source``'s label ahead of the image parts of ``contents``.

    Returned unchanged when there is no source, no image anywhere in the
    contents (a label on pure text would just be noise), or the label is
    already the first item (idempotent - a retried call must not stack
    labels). Unknown sources raise via ``label_for``.

    The label is a plain string: the REST path accepts strings as text
    parts and ``_to_live_parts`` converts them on the Live path, so one
    insertion point covers both send paths.
    """
    if source is None:
        return contents
    label = label_for(source)
    items = list(contents) if isinstance(contents, (list, tuple)) else [contents]
    if not any(is_image_item(i) for i in items):
        return contents
    if items and items[0] == label:
        return contents
    return [label, *items]
